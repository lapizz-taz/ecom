/**
 * Builds the UniBee logo files from the original logo artwork (white wordmark on red).
 *
 * The wordmark is TRACED from the supplied file (not redrawn), so the shapes stay
 * exactly as designed. Run again if you get a higher-resolution master file:
 *
 *   node scripts/make-brand-assets.mjs path/to/logo.png
 *
 * Outputs:
 *   public/brand/unibee-logo-white.svg   white wordmark (for red / dark backgrounds)
 *   public/brand/unibee-logo-red.svg     #FF3333 wordmark (for white backgrounds)
 *   public/brand/unibee-mark-white.svg   the "B" mark only
 *   src/components/brand/logo-paths.ts   path data used by the <Logo /> component
 *   src/app/icon.png (32x32), src/app/apple-icon.png (180x180)
 */
import fs from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";
import potrace from "potrace";

const SRC = process.argv[2];
if (!SRC) throw new Error("Usage: node scripts/make-brand-assets.mjs <logo.png>");

const RED = "#FF3333";
const SCALE = 4; // trace at 4x for smooth curves

// Bounding boxes measured on the 2000x2000 master (white pixels).
const WORDMARK = { left: 562, top: 839, width: 860, height: 272 };
const MARK = { left: 924, top: 839, width: 212, height: 272 };

async function trace(box) {
  const buf = await sharp(SRC)
    .extract(box)
    .resize(box.width * SCALE, box.height * SCALE, { kernel: "lanczos3" })
    .greyscale()
    .blur(2.2) // smooth anti-aliasing steps so the trace has clean edges
    .negate() // potrace traces dark shapes; the logo is white
    .png()
    .toBuffer();
  const svg = await new Promise((resolve, reject) =>
    potrace.trace(buf, { threshold: 72, turdSize: 20, optTolerance: 0.8, alphaMax: 1.1, turnPolicy: "minority" }, (e, s) =>
      e ? reject(e) : resolve(s),
    ),
  );
  const d = [...svg.matchAll(/ d="([^"]+)"/g)]
    .map((m) => m[1])
    .join(" ")
    .replace(/\d+\.\d+/g, (n) => String(Math.round(Number(n)))) // integer precision is plenty at 4x
    .replace(/, /g, ",")
    .replace(/\s+/g, " ");
  return { d, w: box.width * SCALE, h: box.height * SCALE };
}

const svgFile = ({ d, w, h }, fill, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" role="img" aria-label="${title}"><path fill="${fill}" fill-rule="evenodd" d="${d}"/></svg>\n`;

const word = await trace(WORDMARK);
const mark = await trace(MARK);

await fs.writeFile("public/brand/unibee-logo-white.svg", svgFile(word, "#FFFFFF", "UniBee"));
await fs.writeFile("public/brand/unibee-logo-red.svg", svgFile(word, RED, "UniBee"));
await fs.writeFile("public/brand/unibee-mark-white.svg", svgFile(mark, "#FFFFFF", "UniBee"));

await fs.mkdir("src/components/brand", { recursive: true });
await fs.writeFile(
  "src/components/brand/logo-paths.ts",
  `// Generated by scripts/make-brand-assets.mjs. Do not edit by hand.\n` +
    `export const WORDMARK = { w: ${word.w}, h: ${word.h}, d: ${JSON.stringify(word.d)} };\n` +
    `export const MARK = { w: ${mark.w}, h: ${mark.h}, d: ${JSON.stringify(mark.d)} };\n`,
);

// Favicons: white "B" mark centred on a red square.
async function icon(size, file, radius) {
  const pad = Math.round(size * 0.16);
  const inner = size - pad * 2;
  const markPng = await sharp(Buffer.from(svgFile(mark, "#FFFFFF", "UniBee")))
    .resize({ width: inner, height: inner, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
    .png()
    .toBuffer();
  const bg = Buffer.from(
    `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${radius}" fill="${RED}"/></svg>`,
  );
  await sharp(bg).composite([{ input: markPng, top: pad, left: pad }]).png().toFile(file);
}
await icon(32, path.join("src/app", "icon.png"), 6);
await icon(180, path.join("src/app", "apple-icon.png"), 0); // iOS rounds the corners itself
await icon(512, path.join("public/brand", "unibee-icon-512.png"), 0);
console.log("Brand assets written.");
