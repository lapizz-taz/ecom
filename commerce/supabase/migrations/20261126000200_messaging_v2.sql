returns void
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v jsonb := public._messaging_settings();
  k text;
begin
  for k in select jsonb_object_keys(p) loop
    if jsonb_typeof(v -> k) = 'object' and jsonb_typeof(p -> k) = 'object' then
      v := jsonb_set(v, array[k], (v -> k) || (p -> k));
