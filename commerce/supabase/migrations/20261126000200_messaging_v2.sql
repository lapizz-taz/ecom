/** Abandoned carts that got a reminder in the last days, and how many of them were bought. */
create or replace function public._cart_recovery_stats(p_days int default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v jsonb;
begin
  with sent as (
    select distinct regexp_replace(data ->> 'step', ':[0-9]+$', '') as cart_key
    from public.notification_logs
    where event = 'CART_REMINDER' and status = 'SENT' and created_at > now() - make_interval(days => greatest(p_days, 1))
  ), own as (
    select c.id, coalesce(o.total_amount, c.subtotal) as value
    from public.store_carts c
    join sent on sent.cart_key = 'cart:own:' || c.id
    left join public.orders o on o.id = c.order_id
    where c.status = 'CONVERTED'
  ), shop as (
    select s.id, s.total as value
    from public.shopify_abandoned_checkouts s
    join sent on sent.cart_key = 'cart:shopify:' || s.id
    where s.status = 'RECOVERED'
  )
  select jsonb_build_object(
    'days', greatest(p_days, 1),
    'reminded', (select count(*) from sent),
    'recovered', (select count(*) from own) + (select count(*) from shop),
    'recovered_value', coalesce((select sum(value) from own), 0) + coalesce((select sum(value) from shop), 0))
  into v;
  return v;
end;
$$;

