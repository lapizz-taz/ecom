    raise exception 'VALIDATION: choose English or Bangla' using errcode = '22023';
  end if;
  perform public._messaging_put(jsonb_build_object('language', p_language));
  perform public._notification_channel_put('whatsapp', jsonb_build_object('language', p_language));
