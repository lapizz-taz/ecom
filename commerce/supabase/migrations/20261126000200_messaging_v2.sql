--     SMS of the same step. Meta's delivered and read receipts are kept.
--   * Abandoned cart reminders (CART_REMINDER), review requests a few days after
--     delivery (REVIEW_REQUEST) and the owner's daily summary email, queued by the
--     messaging function every 5 minutes (it knows the store's cart links).
--   * Every default text in English and Bangla (SMS too). The store's message
--     language switches the texts nobody changed.
-- Run 20261126000100_messaging_v2_events.sql first. Safe to re-run.
-- =============================================================================

