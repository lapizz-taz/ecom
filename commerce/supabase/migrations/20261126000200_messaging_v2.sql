/** Review requests that are due: delivered the chosen number of days ago (at most 3 days late), never twice. */
create or replace function public.messaging_run_reviews(p_limit int default 100)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  s jsonb := public._messaging_settings() -> 'review';
  v_days int := least(greatest(coalesce((s ->> 'days')::int, 3), 1), 30);
  o record;
  v_count int := 0;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if coalesce(s ->> 'url', '') = '' or not public._messaging_daytime()
     or not exists (select 1 from public.notifications where event = 'REVIEW_REQUEST' and is_enabled) then
    return 0;
  end if;
  for o in
    select x.id from public.orders x
    where x.status = 'DELIVERED' and x.merged_into is null
      and x.delivered_at < now() - make_interval(days => v_days) and x.delivered_at > now() - make_interval(days => v_days + 3)
      and not exists (select 1 from public.notification_logs l where l.order_id = x.id and l.event = 'REVIEW_REQUEST')
    order by x.delivered_at
    limit least(greatest(p_limit, 1), 500)
  loop
    v_count := v_count + public._enqueue_order_notification(o.id, 'REVIEW_REQUEST', 'review', null);
  end loop;
  return v_count;
end;
$$;

/**
 * Carts due a reminder: our store's carts that reached checkout (we have the phone) and Shopify's
 * abandoned checkouts, left at least the chosen time ago and at most 3 days ago; the second
 * reminder the chosen hours after the first when nothing happened since. Day time only.
 */
create or replace function public.messaging_due_carts(p_limit int default 50)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  s jsonb := public._messaging_settings() -> 'cart';
  v_first interval := make_interval(mins => least(greatest(coalesce((s ->> 'first_minutes')::int, 60), 15), 1440));
  v_second boolean := coalesce((s ->> 'second')::boolean, true);
  v_after interval := make_interval(hours => least(greatest(coalesce((s ->> 'second_hours')::int, 24), 2), 72));
  v_limit int := least(greatest(p_limit, 1), 200);
  v jsonb;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if not public._messaging_daytime() or not exists (select 1 from public.notifications where event = 'CART_REMINDER' and is_enabled) then
    return '[]'::jsonb;
  end if;
  with first_own as (
    select 'own' as source, c.id, 1 as step, null::text as url, c.last_activity_at as at
    from public.store_carts c
    where c.status = 'ACTIVE' and c.item_count > 0 and c.phone is not null
      and c.last_activity_at < now() - v_first and c.last_activity_at > now() - interval '3 days'
      and not exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:own:' || c.id || ':1')
  ), first_shop as (
    select 'shopify', s.id, 1, s.recovery_url, coalesce(s.shop_updated_at, s.shop_created_at)
    from public.shopify_abandoned_checkouts s
    where s.status = 'OPEN' and s.follow_up = 'NONE' and s.recovery_url is not null and (s.phone is not null or s.email is not null)
      and coalesce(s.shop_updated_at, s.shop_created_at) < now() - v_first
      and coalesce(s.shop_updated_at, s.shop_created_at) > now() - interval '3 days'
      and not exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:shopify:' || s.id || ':1')
  ), second_own as (
    select 'own', c.id, 2, null::text, c.last_activity_at
    from public.store_carts c
    where v_second and c.status = 'ACTIVE' and c.item_count > 0 and c.phone is not null and c.last_activity_at > now() - interval '5 days'
      and exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:own:' || c.id || ':1'
                  and l.created_at < now() - v_after and l.created_at > c.last_activity_at)
      and not exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:own:' || c.id || ':2')
  ), second_shop as (
    select 'shopify', s.id, 2, s.recovery_url, coalesce(s.shop_updated_at, s.shop_created_at)
    from public.shopify_abandoned_checkouts s
    where v_second and s.status = 'OPEN' and s.follow_up = 'NONE' and s.recovery_url is not null
      and coalesce(s.shop_updated_at, s.shop_created_at) > now() - interval '5 days'
      and exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:shopify:' || s.id || ':1'
                  and l.created_at < now() - v_after and l.created_at > coalesce(s.shop_updated_at, s.shop_created_at))
      and not exists (select 1 from public.notification_logs l where l.data ->> 'step' = 'cart:shopify:' || s.id || ':2')
  ), due as (
    select * from first_own union all select * from first_shop union all select * from second_own union all select * from second_shop
  )
  select coalesce(jsonb_agg(jsonb_build_object('source', d.source, 'id', d.id, 'step', d.step, 'url', d.url) order by d.at), '[]'::jsonb)
  into v
  from (select * from due order by at limit v_limit) d;
  return v;
end;
$$;

/** Queues one cart reminder on every channel that is on (the messaging function passes the link back to the cart). */
create or replace function public.messaging_queue_cart(p_source text, p_id uuid, p_step int, p_url text)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_name text;
  v_phone text;
  v_email text;
  v_items jsonb;
  v_total numeric;
  v_count_items int;
  v_customer uuid;
  v_step text := 'cart:' || p_source || ':' || p_id || ':' || p_step;
  v_symbol text := public.setting_text('store', array['currency_symbol'], '৳');
  v_sms_prefix text := coalesce(nullif(trim(public.setting_text('sms', array['currency_text'], 'Tk')), '') || ' ', '');
  v_email_settings jsonb := public._email_settings();
  v_wa jsonb := public._whatsapp_settings();
  v_tpl public.notifications;
  v_vars jsonb;
  v_sms_vars jsonb;
  v_data jsonb;
  v_recipient text;
  v_body text;
  v_parts record;
  v_key text;
  v_log uuid;
  v_count int := 0;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if p_source not in ('own', 'shopify') or p_step not in (1, 2) or coalesce(p_url, '') !~* '^https?://' then
    raise exception 'VALIDATION: unknown cart' using errcode = '22023';
  end if;
  if p_source = 'own' then
    select c.customer_name, c.phone, c.customer_id,
           (select lower(cu.email) from public.customers cu where cu.id = c.customer_id or (c.customer_id is null and cu.phone = c.phone) limit 1),
           (select coalesce(jsonb_agg(jsonb_build_object('title', e ->> 'name', 'variant_title', e ->> 'variant', 'quantity', (e ->> 'quantity')::int,
                                                         'price', (e ->> 'unit_price')::numeric,
                                                         'line_price', (e ->> 'unit_price')::numeric * (e ->> 'quantity')::int,
                                                         'image_url', e ->> 'image') order by ord), '[]'::jsonb)
            from jsonb_array_elements(c.items) with ordinality as t(e, ord)),
           c.subtotal, c.item_count
    into v_name, v_phone, v_customer, v_email, v_items, v_total, v_count_items
    from public.store_carts c where c.id = p_id and c.status = 'ACTIVE';
  else
    select s.customer_name, s.phone, null::uuid, lower(s.email),
           (select coalesce(jsonb_agg(jsonb_build_object('title', e ->> 'title', 'variant_title', e ->> 'variant', 'quantity', (e ->> 'quantity')::int,
                                                         'price', nullif(e ->> 'price', '')::numeric,
                                                         'line_price', nullif(e ->> 'price', '')::numeric * (e ->> 'quantity')::int,
                                                         'image_url', e ->> 'image') order by ord), '[]'::jsonb)
            from jsonb_array_elements(s.items) with ordinality as t(e, ord)),
           s.total, s.item_count
    into v_name, v_phone, v_customer, v_email, v_items, v_total, v_count_items
    from public.shopify_abandoned_checkouts s where s.id = p_id and s.status = 'OPEN' and s.follow_up = 'NONE';
  end if;
  if v_items is null then
    return 0;
  end if;
  v_vars := jsonb_build_object(
    'customer_name', coalesce(v_name, ''), 'customer_first_name', split_part(trim(coalesce(v_name, '')), ' ', 1),
    'cart_total', public._fmt_amount(v_total, v_symbol), 'cart_url', p_url,
    'store_name', public.setting_text('store', array['name'], 'Our store'), 'store_phone', public.setting_text('store', array['phone'], ''));
  v_sms_vars := v_vars || jsonb_build_object('cart_total', public._fmt_amount(v_total, v_sms_prefix));

  for v_tpl in select * from public.notifications where event = 'CART_REMINDER' and is_enabled order by created_at, id loop
    v_key := v_tpl.id || ':' || v_step;
    v_log := null;
    if v_tpl.channel = 'SMS' then
      if not public.setting_bool('sms', array['enabled'], false) or not public.feature_enabled('sms') then
        continue;
      end if;
      v_recipient := public.sms_phone(v_phone);
      if v_recipient is null or exists (select 1 from public.notification_logs f where f.fallback_of is not null
                                        and f.data ->> 'step' = v_step and f.status in ('QUEUED', 'SENDING', 'SENT')) then
        continue;
      end if;
      v_body := public.render_template(v_tpl.template, v_sms_vars);
      select * into v_parts from public.sms_parts(v_body);
      insert into public.notification_logs(notification_id, event, channel, recipient, body, customer_id, dedupe_key,
        segments, encoding, cost, cost_source, provider, data)
      values (v_tpl.id, 'CART_REMINDER', 'SMS', v_recipient, v_body, v_customer, v_key, v_parts.segments, v_parts.encoding,
        round(v_parts.segments * greatest(public._sms_credit_price(), 0), 4), 'ESTIMATE', public._platform_sms_provider(),
        jsonb_build_object('step', v_step))
      on conflict (merchant_id, dedupe_key) do nothing;
    elsif v_tpl.channel = 'EMAIL' then
      if not coalesce((v_email_settings ->> 'enabled')::boolean, false) or not public._email_ready(v_email_settings)
         or v_email is null or v_email !~* '^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$' then
        continue;
      end if;
      if v_email_settings ->> 'provider' = 'fullfilio' and public._email_service_sent_today() >= public._email_service_limit() then
        continue;
      end if;
      v_data := jsonb_build_object('liquid', true, 'step', v_step, 'vars', jsonb_build_object(
        'shop', public._notification_shop(),
        'customer', jsonb_build_object('name', v_name, 'first_name', split_part(trim(coalesce(v_name, '')), ' ', 1), 'phone', v_phone, 'email', v_email),
        'cart', jsonb_build_object('url', p_url, 'total', v_total, 'item_count', v_count_items, 'line_items', v_items)));
      insert into public.notification_logs(notification_id, event, channel, recipient, subject, body, customer_id, dedupe_key, provider, data)
      values (v_tpl.id, 'CART_REMINDER', 'EMAIL', v_email, v_tpl.subject, v_tpl.template, v_customer, v_key, v_email_settings ->> 'provider', v_data)
      on conflict (merchant_id, dedupe_key) do nothing;
    else
      if not coalesce((v_wa ->> 'enabled')::boolean, false) or coalesce(v_wa ->> 'provider', '') <> 'meta' then
        continue;
      end if;
      v_recipient := public.sms_phone(v_phone);
      if v_recipient is null then
        continue;
      end if;
      v_body := public.render_template(coalesce(v_tpl.wa_body, v_tpl.template), v_vars);
      v_data := jsonb_build_object('vars', v_vars, 'sms_vars', v_sms_vars, 'channel_id', v_wa ->> 'channel_id', 'step', v_step);
      if coalesce(v_tpl.wa_status, '') <> 'APPROVED' or v_tpl.wa_name is null then
        insert into public.notification_logs(notification_id, event, channel, recipient, body, customer_id, dedupe_key, provider, data, status, error)
        values (v_tpl.id, 'CART_REMINDER', 'WHATSAPP', v_recipient, v_body, v_customer, v_key, 'meta', v_data, 'SKIPPED',
          'This WhatsApp message is not approved by Meta yet (WhatsApp → submit it for approval)')
        on conflict (merchant_id, dedupe_key) do nothing
        returning id into v_log;
        if v_log is not null then
          perform public._whatsapp_fallback(v_log);
        end if;
        continue;
      end if;
      insert into public.notification_logs(notification_id, event, channel, recipient, body, customer_id, dedupe_key, provider, data)
      values (v_tpl.id, 'CART_REMINDER', 'WHATSAPP', v_recipient, v_body, v_customer, v_key, 'meta', v_data)
      on conflict (merchant_id, dedupe_key) do nothing;
    end if;
    if found then
      v_count := v_count + 1;
    end if;
  end loop;
  return v_count;
end;
$$;

/**
 * The owner's summary of yesterday, once a day from the chosen hour (Bangladesh time), to the
 * chosen addresses, through the store's email setup.
 */
create or replace function public.messaging_run_summary()
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  s jsonb := public._messaging_settings();
  v_sum jsonb := s -> 'summary';
  v_tz text := public.store_timezone();
  v_today date := (now() at time zone v_tz)::date;
  v_day date := (now() at time zone v_tz)::date - 1;
  v_from timestamptz := ((now() at time zone v_tz)::date - 1)::timestamp at time zone v_tz;
  v_to timestamptz := ((now() at time zone v_tz)::date)::timestamp at time zone v_tz;
  v_email jsonb := public._email_settings();
  v_tpl public.notification_defaults;
  v_stats jsonb;
  v_fin record;
  v_to_addr text;
  v_count int := 0;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if not coalesce((v_sum ->> 'enabled')::boolean, false) then
    return jsonb_build_object('sent', 0, 'reason', 'off');
  end if;
  if extract(hour from now() at time zone v_tz) < coalesce((v_sum ->> 'hour')::int, 9) or coalesce(v_sum ->> 'last_sent', '') = v_today::text then
    return jsonb_build_object('sent', 0, 'reason', 'not_due');
  end if;
  if not coalesce((v_email ->> 'enabled')::boolean, false) or not public._email_ready(v_email) then
    return jsonb_build_object('sent', 0, 'reason', 'email_not_set_up');
  end if;

  select coalesce(sum(amount) filter (where line = 'product_sales'), 0) as ps, coalesce(sum(amount) filter (where line = 'delivery_income'), 0) as di,
         coalesce(sum(amount) filter (where line = 'return_charges'), 0) as rc, coalesce(sum(amount) filter (where line = 'other_income'), 0) as oi,
         coalesce(sum(amount) filter (where line = 'refunds'), 0) as rf, coalesce(sum(amount) filter (where line = 'product_cost'), 0) as pc,
         coalesce(sum(amount) filter (where line = 'delivery_cost'), 0) as dc, coalesce(sum(amount) filter (where line = 'ads'), 0) as ad,
         coalesce(sum(amount) filter (where line = 'other_expense'), 0) as oe
  into v_fin
  from public._fin_rows(v_day, v_day, 'delivered');

  v_stats := jsonb_build_object(
    'date', to_char(v_day, 'DD Mon YYYY'),
    'orders', (select count(*) from public.orders where created_at >= v_from and created_at < v_to and merged_into is null),
    'orders_value', (select coalesce(sum(total_amount), 0) from public.orders where created_at >= v_from and created_at < v_to and merged_into is null),
    'approved', (select count(*) from public.orders where confirmed_at >= v_from and confirmed_at < v_to),
    'shipped', (select count(*) from public.orders where shipped_at >= v_from and shipped_at < v_to),
    'delivered', (select count(*) from public.orders where delivered_at >= v_from and delivered_at < v_to and status in ('DELIVERED', 'PARTIALLY_DELIVERED')),
    'delivered_value', (select coalesce(sum(total_amount), 0) from public.orders
                        where delivered_at >= v_from and delivered_at < v_to and status in ('DELIVERED', 'PARTIALLY_DELIVERED')),
    'returned', (select count(*) from public.orders where returned_at >= v_from and returned_at < v_to),
    'cancelled', (select count(*) from public.orders where cancelled_at >= v_from and cancelled_at < v_to and merged_into is null),
    'ad_spend', v_fin.ad,
    'profit', v_fin.ps + v_fin.di + v_fin.rc + v_fin.oi - v_fin.rf - v_fin.pc - v_fin.dc - v_fin.ad - v_fin.oe,
    'waiting', (select count(*) from public.orders o where o.confirmed_at is null and o.merged_into is null
                  and o.status not in ('CANCELLED', 'REJECTED_FRAUD') and o.created_at > now() - interval '14 days'
                  and not exists (select 1 from public.order_review_statuses rs where rs.code = o.review_status and rs.closes_order)));

  select * into v_tpl from public.notification_defaults where channel = 'EMAIL' and event = 'DAILY_SUMMARY' and language = s ->> 'language';
  for v_to_addr in select distinct lower(e) from jsonb_array_elements_text(coalesce(v_sum -> 'emails', '[]'::jsonb)) e
                   where e ~* '^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$' limit 5 loop
    insert into public.notification_logs(event, channel, recipient, subject, body, purpose, provider, dedupe_key, data)
    values ('DAILY_SUMMARY', 'EMAIL', v_to_addr, v_tpl.subject, v_tpl.template, 'SUMMARY', v_email ->> 'provider',
            'summary:' || v_day || ':' || v_to_addr,
            jsonb_build_object('liquid', true, 'vars', jsonb_build_object('shop', public._notification_shop(), 'summary', v_stats)))
    on conflict (merchant_id, dedupe_key) do nothing;
    if found then
      v_count := v_count + 1;
    end if;
  end loop;
  perform public._messaging_put(jsonb_build_object('summary', jsonb_build_object('last_sent', v_today::text)));
  return jsonb_build_object('sent', v_count);
end;
$$;

-- ---------------------------------------------------------------- order page: Send on WhatsApp
/** The store's WhatsApp texts filled in for one order, for "Send on WhatsApp" (opens the staff member's own WhatsApp). */
create or replace function public.whatsapp_order_messages(p_order_id uuid)
returns jsonb
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_vars jsonb;
  v_phone text;
begin
  perform public.require_permission('orders.view');
  select public.sms_phone(customer_phone) into v_phone from public.orders where id = p_order_id;
  if not found then
    raise exception 'NOT_FOUND: order not found' using errcode = 'P0002';
  end if;
  v_vars := public._notification_vars(p_order_id, public.setting_text('store', array['currency_symbol'], '৳'), null);
  return jsonb_build_object(
    'phone', v_phone,
    'messages', coalesce((
      select jsonb_agg(jsonb_build_object('event', n.event, 'name', coalesce(n.name, public.notification_event_label(n.event)),
                                          'text', public.render_template(n.template, v_vars)) order by array_position(array[
        'ORDER_CREATED', 'ORDER_CONFIRMED', 'PRE_ORDER_CONFIRMED', 'ADVANCE_REQUIRED', 'PAYMENT_RECEIVED', 'PAYMENT_FAILED',
        'ORDER_SHIPPED', 'OUT_FOR_DELIVERY', 'DELIVERY_FAILED', 'ORDER_DELIVERED', 'REVIEW_REQUEST', 'ORDER_CANCELLED',
        'RETURN_INITIATED', 'ORDER_RETURNED'
      ]::public.notification_event[], n.event))
      from public.notifications n where n.channel = 'WHATSAPP' and n.event not in ('ADVANCE_RECEIVED', 'CART_REMINDER')), '[]'::jsonb));
end;
$$;

-- ---------------------------------------------------------------- schedule
do $$
begin
  if not exists (select 1 from pg_extension where extname = 'pg_cron') or not exists (select 1 from pg_extension where extname = 'pg_net') then
    raise notice 'pg_cron or pg_net missing: messaging-scheduled not scheduled';
    return;
  end if;
  perform cron.unschedule(jobid) from cron.job where jobname = 'messaging-scheduled';
  perform cron.schedule('messaging-scheduled', '*/5 * * * *', $job$
  select net.http_post(
    url := 'https://fullfilio.com/functions/v1/messaging',
    headers := jsonb_build_object('Content-Type', 'application/json',
      'x-cron-secret', (select decrypted_secret from vault.decrypted_secrets where name = 'cron_secret')),
    body := '{"action": "scheduled"}'::jsonb,
    timeout_milliseconds := 60000)
  where public.messaging_scheduled_due()
$job$);
end $$;

