create or replace function public.messaging_settings_save(p jsonb)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v jsonb := '{}'::jsonb;
  x jsonb;
  v_emails jsonb;
begin
  perform public.require_permission('notifications.manage');
  if jsonb_typeof(p -> 'confirm') = 'object' then
    v := v || jsonb_build_object('confirm', jsonb_build_object('auto_approve', coalesce((p #>> '{confirm,auto_approve}')::boolean, false)));
  end if;
  if jsonb_typeof(p -> 'cart') = 'object' then
    x := p -> 'cart';
    if coalesce((x ->> 'first_minutes')::int, 60) not between 15 and 1440 then
      raise exception 'VALIDATION: send the first reminder between 15 minutes and 24 hours after the cart is left' using errcode = '22023';
    end if;
    if coalesce((x ->> 'second_hours')::int, 24) not between 2 and 72 then
      raise exception 'VALIDATION: send the second reminder between 2 and 72 hours after the first' using errcode = '22023';
    end if;
    v := v || jsonb_build_object('cart', jsonb_build_object(
      'first_minutes', coalesce((x ->> 'first_minutes')::int, 60),
      'second', coalesce((x ->> 'second')::boolean, true),
      'second_hours', coalesce((x ->> 'second_hours')::int, 24)));
  end if;
  if jsonb_typeof(p -> 'review') = 'object' then
    x := p -> 'review';
    if coalesce((x ->> 'days')::int, 3) not between 1 and 30 then
      raise exception 'VALIDATION: ask for a review 1 to 30 days after delivery' using errcode = '22023';
    end if;
    if coalesce(x ->> 'url', '') <> '' and ((x ->> 'url') !~* '^https?://[^\s/]+\.[^\s]+$' or length(x ->> 'url') > 500) then
      raise exception 'VALIDATION: enter the full review link, starting with https://' using errcode = '22023';
    end if;
    v := v || jsonb_build_object('review', jsonb_build_object('days', coalesce((x ->> 'days')::int, 3), 'url', trim(coalesce(x ->> 'url', ''))));
  end if;
  if jsonb_typeof(p -> 'summary') = 'object' then
    x := p -> 'summary';
    if coalesce((x ->> 'hour')::int, 9) not between 0 and 23 then
      raise exception 'VALIDATION: choose an hour between 0 and 23' using errcode = '22023';
    end if;
    select coalesce(jsonb_agg(distinct lower(trim(e))), '[]'::jsonb) into v_emails
    from jsonb_array_elements_text(case when jsonb_typeof(x -> 'emails') = 'array' then x -> 'emails' else '[]'::jsonb end) e
    where trim(e) <> '';
    if jsonb_array_length(v_emails) > 5 then
      raise exception 'VALIDATION: send the summary to at most 5 addresses' using errcode = '22023';
    end if;
    if exists (select 1 from jsonb_array_elements_text(v_emails) e where e !~* '^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$') then
      raise exception 'VALIDATION: one of the email addresses is not valid' using errcode = '22023';
    end if;
    if coalesce((x ->> 'enabled')::boolean, false) and jsonb_array_length(v_emails) = 0 then
      raise exception 'VALIDATION: add the email address the summary goes to' using errcode = '22023';
    end if;
    v := v || jsonb_build_object('summary', jsonb_build_object(
      'enabled', coalesce((x ->> 'enabled')::boolean, false), 'hour', coalesce((x ->> 'hour')::int, 9), 'emails', v_emails));
  end if;
  perform public._messaging_put(v);
  return public.messaging_settings();
end;
$$;

/**
 * The store's message language. With p_apply, every SMS, email and WhatsApp text that is still a
 * default (in any language) becomes the default in the new language; texts staff wrote stay.
 * WhatsApp texts in a new language need Meta's approval again.
 */
create or replace function public.messaging_language_set(p_language text, p_apply boolean default true)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_changed int := 0;
  v_custom int;
begin
  perform public.require_permission('notifications.manage');
