/**
 * The customer's answer (a WhatsApp button or the email page). Confirm: the web order becomes
 * "Customer confirmed" (approved too when the store chose that and nothing needs a check).
 * Cancel before approval: cancelled. Cancel after approval: a request on the order for the team.
 * A WhatsApp answer must come from the order's own number.
 */
create or replace function public.order_reply_apply(p_token text, p_action text, p_via text, p_phone text default null)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  t public.order_reply_tokens;
  o public.orders;
  v_state text;
  v_result text;
  v_settings jsonb := public._messaging_settings();
  v_how text := case p_via when 'WHATSAPP' then 'on WhatsApp' else 'by email' end;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if p_action not in ('confirm', 'cancel') or p_via not in ('WHATSAPP', 'EMAIL') then
    raise exception 'VALIDATION: unknown answer' using errcode = '22023';
  end if;
  if coalesce(p_token, '') !~ '^[0-9a-f]{40}$' then
    return jsonb_build_object('result', 'not_found');
  end if;
  select * into t from public.order_reply_tokens where token = p_token for update;
  if not found then
    return jsonb_build_object('result', 'not_found');
  end if;
  select * into o from public.orders where id = t.order_id;
  if o.merged_into is not null then
    select * into o from public.orders where id = o.merged_into;
  end if;
  select * into o from public.orders where id = o.id for update;
  if p_phone is not null and public.sms_phone(p_phone) is distinct from public.sms_phone(o.customer_phone) then
    return jsonb_build_object('result', 'ignored', 'order_number', o.order_number);
  end if;
  v_state := public._order_reply_state(o, t);

  if v_state = 'EXPIRED' then
    v_result := 'closed';
  elsif p_action = 'confirm' then
    if v_state = 'OPEN' then
      insert into public.order_review_statuses (merchant_id, code, label, description, color, closes_order, needs_follow_up,
                                                counts_contact, is_system, is_active, sort_order)
      values (o.merchant_id, 'CUSTOMER_CONFIRMED', 'Customer confirmed', 'The customer confirmed the order on WhatsApp or by email',
              'success', false, false, false, true, true, 15)
      on conflict do nothing;
      update public.orders set review_status = 'CUSTOMER_CONFIRMED', review_note = 'Confirmed by the customer ' || v_how,
        review_updated_at = now(), review_updated_by = null
      where id = o.id;
      perform public._order_log(o.id, 'REVIEW_STATUS', 'Customer confirmed ' || v_how, null, null,
        jsonb_build_object('from', o.review_status, 'to', 'CUSTOMER_CONFIRMED', 'via', p_via));
      if coalesce((v_settings #>> '{confirm,auto_approve}')::boolean, false) and o.status in ('PENDING', 'CONFIRMATION_REQUIRED') then
        begin
          perform public._transition_order(o.id, 'CONFIRMED', 'Approved: the customer confirmed ' || v_how);
        exception when others then
          perform public._order_log(o.id, 'NOTE', 'Not approved automatically: ' || sqlerrm);
        end;
      end if;
      update public.order_reply_tokens set reply = 'CONFIRMED', replied_at = now(), reply_via = p_via where order_id = t.order_id;
      v_result := 'confirmed';
    elsif v_state = 'CONFIRMED' then
      v_result := 'confirmed';
    elsif v_state = 'CANCELLED' then
      v_result := 'cancelled';
    else
      v_result := 'closed';
    end if;
  else
    if v_state = 'CANCELLED' then
      v_result := 'cancelled';
    elsif v_state in ('CLOSED', 'CANCEL_REQUESTED') then
      v_result := case when v_state = 'CANCEL_REQUESTED' then 'cancel_requested' else 'closed' end;
    elsif o.confirmed_at is null then
      begin
        perform public._transition_order(o.id, 'CANCELLED', 'Cancelled by the customer ' || v_how);
        update public.orders set review_status = 'CANCELLED', review_note = 'Cancelled by the customer ' || v_how,
          review_updated_at = now(), review_updated_by = null
        where id = o.id and exists (select 1 from public.order_review_statuses s where s.merchant_id = o.merchant_id and s.code = 'CANCELLED');
        update public.order_reply_tokens set reply = 'CANCELLED', replied_at = now(), reply_via = p_via where order_id = t.order_id;
        v_result := 'cancelled';
      exception when others then
        v_result := null;
      end;
    end if;
    if v_result is null then
      -- Approved already (or it could not be cancelled here): the team decides, before the parcel goes out.
      perform public._order_log(o.id, 'CUSTOMER_REQUEST', 'The customer asked to cancel ' || v_how || '. Call them before the parcel ships.',
        null, null, jsonb_build_object('via', p_via));
      update public.order_reply_tokens set reply = 'CANCEL_REQUESTED', replied_at = now(), reply_via = p_via where order_id = t.order_id;
      v_result := 'cancel_requested';
    end if;
  end if;
  return jsonb_build_object('result', v_result, 'order_number', o.order_number, 'language', v_settings ->> 'language',
    -- WhatsApp sends the "cancelled" template itself when it is on: no second chat reply.
    'reply_in_chat', not (v_result = 'cancelled' and exists (
      select 1 from public.notifications n where n.channel = 'WHATSAPP' and n.event = 'ORDER_CANCELLED' and n.is_enabled and n.wa_status = 'APPROVED')));
end;
$$;

