/** Where an order stands for the customer's confirm / cancel. */
create or replace function public._order_reply_state(o public.orders, t public.order_reply_tokens)
returns text
language sql
stable
set search_path = public, pg_temp
as $$
  select case
    when t.created_at < now() - interval '30 days' then 'EXPIRED'
    when o.status in ('CANCELLED', 'REJECTED_FRAUD') then 'CANCELLED'
    when o.shipped_at is not null or o.status in ('SHIPPED', 'DELIVERED', 'PARTIALLY_DELIVERED', 'PENDING_CANCEL', 'RETURN_REQUESTED',
                                                    'RETURNING', 'RETURNED', 'FAILED_DELIVERY', 'LOST') then 'CLOSED'
    when t.reply = 'CANCEL_REQUESTED' then 'CANCEL_REQUESTED'
    when o.confirmed_at is not null or o.review_status = 'CUSTOMER_CONFIRMED' then 'CONFIRMED'
    else 'OPEN' end
$$;

