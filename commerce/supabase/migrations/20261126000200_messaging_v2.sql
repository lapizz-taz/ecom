--     after approval a cancel becomes a request for the team.
--   * "Courier could not reach you" (DELIVERY_FAILED) when a parcel goes on hold
--     or a delivery attempt fails after pickup (at most once a day per parcel).
--   * WhatsApp → SMS: when the store turns it on, a WhatsApp message that cannot
