-- ---------------------------------------------------------------- queue
create or replace function public._enqueue_order_notification(
  p_order_id uuid,
  p_event public.notification_event,
  p_ref text,
  p_extra jsonb
)
returns int
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders;
  v_tpl public.notifications;
  v_vars jsonb;
  v_data jsonb;
  v_facts jsonb;
  v_symbol text;
  v_sms_prefix text;
  v_rate numeric;
  v_recipient text;
  v_body text;
  v_parts record;
  v_key text;
  v_step text := p_order_id || ':' || coalesce(p_ref, p_event::text);
  v_count int := 0;
  v_payment numeric;
  v_email jsonb;
  v_wa jsonb;
  v_courier uuid;
  v_token text;
  v_log uuid;
begin
  if not exists (select 1 from public.notifications where event = p_event and is_enabled) then
    return 0;
  end if;

  begin
    if not public.setting_bool('notifications', array['enabled'], true) then
      return 0;
    end if;
    v_symbol := public.setting_text('store', array['currency_symbol'], '৳');
    v_sms_prefix := nullif(trim(public.setting_text('sms', array['currency_text'], 'Tk')), '');
    v_rate := greatest(public._sms_credit_price(), 0);
    v_payment := nullif(p_extra ->> 'payment_amount', '')::numeric;
    v_email := public._email_settings();
    v_wa := public._whatsapp_settings();
    select * into v_order from public.orders where id = p_order_id;
    if not found then
      return 0;
    end if;
    select s.courier_id into v_courier from public.shipments s
    where s.order_id = p_order_id and s.is_active order by s.created_at desc limit 1;
    v_facts := jsonb_build_object(
      'payment_method', v_order.payment_method,
      'total', v_order.total_amount,
      'district', v_order.shipping_district,
      'source', v_order.source,
      'courier', v_courier,
      'first_order', not exists (select 1 from public.orders o
                                 where o.customer_id = v_order.customer_id and o.id <> v_order.id
                                   and o.created_at < v_order.created_at)
    );

    for v_tpl in select * from public.notifications where event = p_event and is_enabled order by created_at, id loop
      if v_tpl.channel = 'SMS' then
        if not public.setting_bool('sms', array['enabled'], false) or not public.feature_enabled('sms') then
          continue;
        end if;
      elsif v_tpl.channel = 'EMAIL' then
        if not coalesce((v_email ->> 'enabled')::boolean, false) or not public._email_ready(v_email) then
          continue;
        end if;
      elsif not coalesce((v_wa ->> 'enabled')::boolean, false) or coalesce(v_wa ->> 'provider', '') <> 'meta' then
        continue;
      end if;
      if not public._notification_conditions_match(v_tpl.conditions, v_facts) then
        continue;
      end if;
      v_key := v_tpl.id || ':' || v_step;
      v_log := null;
      -- The order confirmation asks the customer to confirm: the order's token goes with it.
      v_token := case when p_event = 'ORDER_CREATED'
                        and ((v_tpl.channel = 'EMAIL' and v_tpl.reply_buttons) or (v_tpl.channel = 'WHATSAPP' and v_tpl.wa_buttons))
                      then public._order_reply_token(p_order_id) end;

      if v_tpl.channel = 'SMS' then
        -- The WhatsApp message of this step already went as an SMS instead: not a second one.
        if exists (select 1 from public.notification_logs f where f.order_id = p_order_id and f.fallback_of is not null
                   and f.data ->> 'step' = v_step and f.status in ('QUEUED', 'SENDING', 'SENT')) then
          continue;
        end if;
        -- SMS amounts use plain text ("Tk 1,250") so messages stay in the cheaper GSM encoding.
        v_vars := public._notification_vars(p_order_id, coalesce(v_sms_prefix || ' ', ''), v_payment);
        v_body := public.render_template(v_tpl.template, v_vars);
        v_recipient := public.sms_phone(v_order.customer_phone);
        select * into v_parts from public.sms_parts(v_body);
        if v_recipient is null then
          insert into public.notification_logs(notification_id, event, channel, recipient, body, order_id, customer_id,
            status, error, dedupe_key, segments, encoding, provider, data)
          values (v_tpl.id, p_event, 'SMS', coalesce(nullif(v_order.customer_phone, ''), '—'), v_body, p_order_id,
            v_order.customer_id, 'SKIPPED', 'Not a Bangladesh mobile number', v_key, v_parts.segments, v_parts.encoding,
            public._platform_sms_provider(), jsonb_build_object('step', v_step))
          on conflict (merchant_id, dedupe_key) do nothing;
          continue;
        end if;
        insert into public.notification_logs(notification_id, event, channel, recipient, body, order_id, customer_id,
          dedupe_key, segments, encoding, cost, cost_source, provider, data)
        values (v_tpl.id, p_event, 'SMS', v_recipient, v_body, p_order_id, v_order.customer_id, v_key,
          v_parts.segments, v_parts.encoding, round(v_parts.segments * v_rate, 4), 'ESTIMATE',
          public._platform_sms_provider(), jsonb_build_object('step', v_step))
        on conflict (merchant_id, dedupe_key) do nothing;

      elsif v_tpl.channel = 'EMAIL' then
        -- Most cash-on-delivery customers give no email: nothing to send, nothing to log.
        v_recipient := lower(trim(v_order.customer_email));
        if v_recipient is null or v_recipient !~* '^[^\s@<>"]+@[^\s@<>"]+\.[a-z]{2,}$' then
          continue;
        end if;
        -- The template and the order as they are now; the sender renders the email.
        v_data := jsonb_build_object('liquid', true, 'vars', public._notification_data(p_order_id, v_payment), 'step', v_step)
          || case when v_token is not null then jsonb_build_object('reply_token', v_token) else '{}'::jsonb end;
        if v_email ->> 'provider' = 'fullfilio' and public._email_service_sent_today() >= public._email_service_limit() then
          insert into public.notification_logs(notification_id, event, channel, recipient, subject, body, order_id,
            customer_id, dedupe_key, provider, data, status, error)
          values (v_tpl.id, p_event, 'EMAIL', v_recipient, v_tpl.subject, v_tpl.template, p_order_id, v_order.customer_id,
            v_key, 'fullfilio', v_data, 'SKIPPED',
            format('Today''s limit of %s emails through Fullfilio''s email service is used up. Connect your own mailbox to send more.', public._email_service_limit()))
          on conflict (merchant_id, dedupe_key) do nothing;
          continue;
        end if;
        insert into public.notification_logs(notification_id, event, channel, recipient, subject, body, order_id,
          customer_id, dedupe_key, provider, data)
        values (v_tpl.id, p_event, 'EMAIL', v_recipient, v_tpl.subject, v_tpl.template, p_order_id, v_order.customer_id,
          v_key, v_email ->> 'provider', v_data)
        on conflict (merchant_id, dedupe_key) do nothing;

      else
        v_vars := public._notification_vars(p_order_id, v_symbol, v_payment);
        v_recipient := public.sms_phone(v_order.customer_phone);
        -- What goes out is the text Meta approved (wa_body), not later edits.
        v_body := public.render_template(coalesce(v_tpl.wa_body, v_tpl.template), v_vars);
        v_data := jsonb_build_object('vars', v_vars, 'channel_id', v_wa ->> 'channel_id', 'step', v_step, 'payment', v_payment)
          || case when v_token is not null then jsonb_build_object('reply_token', v_token) else '{}'::jsonb end;
        if v_recipient is null or coalesce(v_tpl.wa_status, '') <> 'APPROVED' or v_tpl.wa_name is null then
          insert into public.notification_logs(notification_id, event, channel, recipient, body, order_id, customer_id,
            dedupe_key, provider, data, status, error)
          values (v_tpl.id, p_event, 'WHATSAPP', coalesce(v_recipient, nullif(v_order.customer_phone, ''), '—'), v_body, p_order_id,
            v_order.customer_id, v_key, 'meta', v_data, 'SKIPPED',
            case when v_recipient is null then 'Not a Bangladesh mobile number'
                 else 'This WhatsApp message is not approved by Meta yet (WhatsApp → submit it for approval)' end)
          on conflict (merchant_id, dedupe_key) do nothing
          returning id into v_log;
          -- Not approved yet: the SMS of the same step instead, when the store asked for that.
          if v_log is not null and v_recipient is not null then
            perform public._whatsapp_fallback(v_log);
          end if;
          continue;
        end if;
        insert into public.notification_logs(notification_id, event, channel, recipient, body, order_id, customer_id,
          dedupe_key, provider, data)
        values (v_tpl.id, p_event, 'WHATSAPP', v_recipient, v_body, p_order_id, v_order.customer_id, v_key, 'meta', v_data)
        on conflict (merchant_id, dedupe_key) do nothing;
      end if;
      if found then
        v_count := v_count + 1;
      end if;
    end loop;
  exception when others then
    -- A broken template or setting must never stop the order change itself.
    perform public._log_system_event('ERROR', 'SMS', '_enqueue_order_notification',
      format('Could not queue the %s message for an order: %s', public.notification_event_label(p_event), sqlerrm),
      jsonb_build_object('order_id', p_order_id, 'event', p_event, 'sqlstate', sqlstate));
    return 0;
  end;
  return v_count;
end;
$$;

-- ---------------------------------------------------------------- WhatsApp → SMS
/**
 * A WhatsApp message that cannot reach the customer goes as the SMS of the same step, when the
 * store turned that on and SMS is on. Not when the customer already gets an SMS for that step.
 * Returns the SMS log id (null: none).
 */
create or replace function public._whatsapp_fallback(p_log_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  l public.notification_logs;
  v_tpl public.notifications;
  v_step text;
  v_vars jsonb;
  v_body text;
  v_parts record;
  v_id uuid;
begin
  select * into l from public.notification_logs where id = p_log_id and channel = 'WHATSAPP';
  if not found or l.purpose <> 'AUTOMATION' or l.data is null then
    return null;
  end if;
  v_step := l.data ->> 'step';
  if v_step is null or not coalesce((public._whatsapp_settings() ->> 'sms_fallback')::boolean, false)
     or not public.setting_bool('sms', array['enabled'], false) or not public.feature_enabled('sms')
     or public.sms_phone(l.recipient) is null then
    return null;
  end if;
  if exists (select 1 from public.notification_logs s
             where s.channel = 'SMS' and s.data ->> 'step' = v_step and s.status in ('QUEUED', 'SENDING', 'SENT')) then
    return null;
  end if;
  select * into v_tpl from public.notifications
  where channel = 'SMS' and event = l.event
  order by is_enabled desc, created_at, id limit 1;
  if not found then
    return null;
  end if;
  -- SMS amounts in plain text (cheaper GSM encoding): the order's values again, or the cart's SMS values.
  v_vars := case when l.order_id is not null
    then public._notification_vars(l.order_id, coalesce(nullif(trim(public.setting_text('sms', array['currency_text'], 'Tk')), '') || ' ', ''),
                                   nullif(l.data ->> 'payment', '')::numeric)
    else coalesce(l.data -> 'sms_vars', l.data -> 'vars', '{}'::jsonb) end;
  v_body := public.render_template(v_tpl.template, v_vars);
  select * into v_parts from public.sms_parts(v_body);
  insert into public.notification_logs(notification_id, event, channel, recipient, body, order_id, customer_id, dedupe_key,
    segments, encoding, cost, cost_source, provider, data, fallback_of)
  values (v_tpl.id, l.event, 'SMS', public.sms_phone(l.recipient), v_body, l.order_id, l.customer_id, 'fallback:' || l.id,
    v_parts.segments, v_parts.encoding, round(v_parts.segments * greatest(public._sms_credit_price(), 0), 4), 'ESTIMATE',
    public._platform_sms_provider(), jsonb_build_object('step', v_step), l.id)
  on conflict (merchant_id, dedupe_key) do nothing
  returning id into v_id;
  return v_id;
end;
$$;

/** The sender's result; a WhatsApp message that finally failed goes by SMS when the store asked for that. */
create or replace function public.complete_notification(p_id uuid, p_success boolean, p_provider text, p_provider_message_id text, p_error text,
  p_cost numeric default null, p_permanent boolean default false, p_delivery_status text default null)
returns text
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_log public.notification_logs;
  u public.service_usage;
  -- Provider charges are the platform's cost; only unmetered (own-business) accounts see them as their cost.
  v_own_cost boolean;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  select * into u from public.service_usage s
  where s.merchant_id = (select merchant_id from public.notification_logs where id = p_id) and s.idempotency_key = 'sms:' || p_id;
  v_own_cost := u.id is null or u.charge = 'PLAN';
  update public.notification_logs set
    status = case when p_success then 'SENT' when p_permanent or attempts >= 3 then 'FAILED' else 'QUEUED' end::public.notification_status,
    provider = coalesce(p_provider, provider),
    provider_message_id = case when p_success then left(p_provider_message_id, 120) else provider_message_id end,
    error = case when p_success then null else left(p_error, 1000) end,
    sent_at = case when p_success then now() else sent_at end,
    next_attempt_at = case when p_success then next_attempt_at else now() + make_interval(mins => 5 * attempts) end,
    cost = case when p_success and v_own_cost and p_cost is not null and p_cost >= 0 then p_cost else cost end,
    cost_source = case when p_success and v_own_cost and p_cost is not null and p_cost >= 0 then 'PROVIDER' else cost_source end,
    delivery_status = case
      when p_success and channel = 'SMS' then
        case when p_delivery_status in ('PENDING', 'DELIVERED', 'FAILED', 'UNKNOWN') then p_delivery_status else 'UNKNOWN' end
      when p_success and channel = 'WHATSAPP' then 'PENDING'
      else delivery_status end,
    delivered_at = case when p_success and p_delivery_status = 'DELIVERED' then now() else delivered_at end
  where id = p_id and status = 'SENDING'
  returning * into v_log;
  if v_log.id is null then
    return null;
  end if;
  if u.id is not null then
    if v_log.status = 'SENT' then
      perform public._usage_finish(u.id, true, null, p_cost, case when p_delivery_status = 'DELIVERED' then 'DELIVERED' end);
    elsif v_log.status = 'FAILED' then
      perform public._usage_finish(u.id, false, p_error);
    end if;
  end if;
  if v_log.status = 'SENT' then
    perform public._post_sms_finance(p_id);
  elsif v_log.status = 'FAILED' and v_log.channel = 'WHATSAPP' then
    perform public._whatsapp_fallback(v_log.id);
  end if;
  return v_log.status::text;
end;
$$;

/** Meta's receipt for a WhatsApp message we sent: delivered, read, or failed (then the SMS, when on). */
create or replace function public.notification_whatsapp_status(p_message_id text, p_status text, p_error text default null)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_log public.notification_logs;
begin
  if not public.is_system_context() then
    raise exception 'PERMISSION_DENIED' using errcode = '42501';
  end if;
  if p_status not in ('DELIVERED', 'READ', 'FAILED') or coalesce(p_message_id, '') = '' then
    return false;
  end if;
  update public.notification_logs set
    delivery_status = case
      when p_status = 'FAILED' then case when delivery_status in ('DELIVERED', 'READ') then delivery_status else 'FAILED' end
      when p_status = 'DELIVERED' and delivery_status = 'READ' then 'READ'
      else p_status end,
    delivered_at = case when p_status in ('DELIVERED', 'READ') then coalesce(delivered_at, now()) else delivered_at end,
    read_at = case when p_status = 'READ' then coalesce(read_at, now()) else read_at end,
    error = case when p_status = 'FAILED' and delivery_status not in ('DELIVERED', 'READ') then left(coalesce(p_error, 'Meta could not deliver it'), 1000) else error end,
    status_checked_at = now()
  where channel = 'WHATSAPP' and provider = 'meta' and provider_message_id = p_message_id and status = 'SENT'
  returning * into v_log;
  if v_log.id is null then
    return false;
  end if;
  if p_status = 'FAILED' and v_log.delivery_status = 'FAILED' then
    perform public._whatsapp_fallback(v_log.id);
  end if;
  return true;
end;
$$;

