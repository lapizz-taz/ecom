-- ---------------------------------------------------------------- courier could not reach the customer
create or replace function public._shipment_status_notifications()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_open boolean;
begin
  if not new.is_active then
    return null;
  end if;
  select o.status not in ('DELIVERED', 'PARTIALLY_DELIVERED', 'RETURN_REQUESTED', 'RETURNING', 'RETURNED',
                          'CANCELLED', 'REJECTED_FRAUD', 'LOST')
  into v_open from public.orders o where o.id = new.order_id;
  if new.status = 'OUT_FOR_DELIVERY' and v_open then
    -- At most one a day: a parcel can go out again after a failed attempt.
    perform public._enqueue_order_notification(new.order_id, 'OUT_FOR_DELIVERY',
      new.id || ':' || (now() at time zone public.store_timezone())::date, null);
  elsif new.status in ('FAILED', 'ON_HOLD') and old.status in ('PICKED_UP', 'IN_TRANSIT', 'OUT_FOR_DELIVERY') and v_open then
    -- On its way and the courier could not hand it over: ask the customer to call before it turns into a return.
    perform public._enqueue_order_notification(new.order_id, 'DELIVERY_FAILED',
      new.id || ':failed:' || (now() at time zone public.store_timezone())::date, null);
  elsif new.status = 'RETURNING' then
    perform public._enqueue_order_notification(new.order_id, 'RETURN_INITIATED', null, null);
  end if;
  return null;
end;
$$;

